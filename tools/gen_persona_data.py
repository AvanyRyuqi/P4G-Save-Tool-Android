#!/usr/bin/env python3
"""Regenerates app/src/main/assets/www/persona-data.js from aqiu384/megaten-fusion-tool (Unlicense).

    git clone https://github.com/aqiu384/megaten-fusion-tool
    python tools/gen_persona_data.py megaten-fusion-tool

Output is keyed by the Persona ids used in the save file (db.js). Names that are spelled
differently in the source are mapped through ALIASES. Skills become save-file skill ids.
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WWW = ROOT / 'app/src/main/assets/www'

# name in db.js -> name in the source
ALIASES = {
    'Oukuninushi': 'Okuninushi', 'Hitokotonusi': 'Hitokoto-Nushi', 'Seiryuu': 'Seiryu', 'Ikusa': 'Yomotsu-Ikusa',
    'Yamatano-Orochi': 'Yamata-no-Orochi', 'Sui-ki': 'Sui-Ki', 'Fuu-ki': 'Fuu-Ki', 'Andra': 'Andras', 'Kin-ki': 'Kin-Ki',
    'Ongyo-ki': 'Ongyo-Ki', 'Kushinada': 'Kushinada-Hime', 'Laksmi': 'Lakshmi',
}
# Evolved party Personas: the source only stores their resistances, inside the first-tier entry.
# id -> (first-tier name, resistance key)
EVOLVED = {
    193: ('Jiraiya', 'sesists'), 195: ('Tomoe', 'sesists'), 197: ('Konohana Sakuya', 'sesists'),
    199: ('Take-Mikazuchi', 'sesists'), 201: ('Himiko', 'sesists'), 203: ('Kintoki-Douji', 'sesists'),
    205: ('Sukuna-Hikona', 'sesists'),
    207: ('Jiraiya', 'sfsists'), 208: ('Tomoe', 'sfsists'), 209: ('Konohana Sakuya', 'sfsists'),
    210: ('Take-Mikazuchi', 'sfsists'), 211: ('Himiko', 'sfsists'), 212: ('Kintoki-Douji', 'sfsists'),
    213: ('Sukuna-Hikona', 'sfsists'),
}
# db.js lists Magatsu-Izanagi twice. 249 (inside the Golden block) is used for fusion;
# 206 (inside the party block) gets the same data but is never offered as a result or ingredient.
SECONDARY_IDS = {206}


def main(src):
    src = pathlib.Path(src)
    data = src / 'src/app/p4/data'
    load = lambda name: json.loads((data / name).read_text(encoding='utf-8'))
    text = (WWW / 'db.js').read_text(encoding='utf-8')
    names = json.loads(text[text.index('{'):text.rindex('}') + 1])['personae']

    # Same precedence as the source's Persona 4 Golden config: a later file replaces the whole entry.
    source = {}
    for f in ('demon-data.json', 'golden-demon-data.json', 'golden-party-data.json'):
        source.update(load(f))
    skill_ids = {}
    for f in ('skill-data.json', 'golden-skill-data.json'):
        for key, row in load(f).items():
            skill_ids[row['a'][0]] = int(key)

    personas, id_of = {}, {}
    for pid, name in enumerate(names):
        if pid in EVOLVED:
            base, key = EVOLVED[pid]
            personas[pid] = {'r': source[base]['race'].replace(' P', ''), 'x': source[base][key], 'p': 2}
            continue
        entry = source.get(ALIASES.get(name, name))
        if entry is None:
            continue
        party = entry.get('fusion') == 'party'
        # Skill "levels" below 1 are innate skills (in order); 100 and above are special unlock codes.
        learned = sorted((lv, skill_ids[s]) for s, lv in entry['skills'].items() if lv < 100)
        out = {'r': entry['race'].replace(' P', ''), 'l': entry['lvl'], 's': entry['stats'], 'x': entry['resists'],
               'k': [[sid, 0 if lv < 1 else lv] for lv, sid in learned]}
        if party:
            out['p'] = 1
        if pid in SECONDARY_IDS:
            out['a'] = 1
        else:
            id_of[ALIASES.get(name, name)] = pid
        personas[pid] = out

    missing = sorted(set(source) - set(id_of))
    if missing:
        sys.exit('source Personas without a db.js id: %s' % missing)

    chart = load('golden-fusion-chart.json')
    # One cell of the source's Golden chart is misspelled (Empress x Lovers; its non-Golden chart says Hanged).
    chart['table'] = [['Hanged' if c == 'Hang' else c for c in row] for row in chart['table']]
    unknown = {c for row in chart['table'] for c in row} - set(chart['races']) - {'-'}
    if unknown:
        sys.exit('unknown arcana in the fusion chart: %s' % sorted(unknown))
    special = {id_of[k]: [id_of[n] for n in v] for k, v in load('special-recipes.json').items()}
    unlock = {}
    for group in load('golden-demon-unlocks.json'):
        for keys, condition in group['conditions'].items():
            for k in keys.split(','):
                unlock[id_of[k]] = condition

    commit = subprocess.run(['git', '-C', str(src), 'rev-parse', '--short', 'HEAD'],
                            capture_output=True, text=True).stdout.strip()
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    body = ',\n'.join('"%d":%s' % (k, dump(v)) for k, v in sorted(personas.items()))
    target = WWW / 'persona-data.js'
    target.write_text(
        '/* Generated by tools/gen_persona_data.py - do not edit.\n'
        ' * Source: https://github.com/aqiu384/megaten-fusion-tool %s (Unlicense, public domain). */\n'
        'window.P4G_PERSONA_DATA={\n'
        '"chart":%s,\n"special":%s,\n"unlock":%s,\n"personas":{\n%s\n}};\n'
        % (commit, dump(chart), dump(special), dump(unlock), body), encoding='utf-8')
    print('%d personas, %d special recipes -> %s' % (len(personas), len(special), target))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
