#!/usr/bin/env python3
"""Regenerates app/src/main/assets/www/shadow-data.js from aqiu384/megaten-fusion-tool (Unlicense).

    git clone https://github.com/aqiu384/megaten-fusion-tool
    python tools/gen_shadow_data.py megaten-fusion-tool

Enemy names, areas and drops are kept as the source spells them.
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WWW = ROOT / 'app/src/main/assets/www'

# Story order. Every area string of the source must mention at least one of these.
DUNGEONS = ["Yukiko's Castle", 'Steamy Bathhouse', 'Marukyu Striptease', 'Void Quest', 'Secret Lab', 'Heaven',
            'Magatsu Inaba', 'Magatsu Mandala', 'Yomotsu Hirasaka', 'Hollow Forest']
# Source resistance letters -> the app's codes. The source's tables group "Z" with weak, and the digits,
# "S" and "T" with normal (see resistCodes in src/app/p4/data/comp-config.json).
RESIST = {'w': 'w', 'Z': 'w', 's': 's', 'n': 'n', 'N': 'n', 'r': 'r', 'd': 'd', '-': '-', 'S': '-', 'T': '-',
          '2': '-', '3': '-', '4': '-', '5': '-', '9': '-'}
# Skill element codes that deal damage, in the order of the app's element columns.
ATTACKS = ['phy', 'fir', 'ice', 'ele', 'win', 'lig', 'dar', 'alm']


def main(src):
    src = pathlib.Path(src)
    data = src / 'src/app/p4/data'
    load = lambda name: json.loads((data / name).read_text(encoding='utf-8'))

    # Same precedence as the source's Persona 4 Golden config: a later file replaces the whole entry.
    enemies = {}
    for f in ('enemy-data.json', 'golden-enemy-data.json'):
        enemies.update(load(f))
    elem_of = {}
    for f in ('skill-data.json', 'golden-skill-data.json'):
        for row in load(f).values():
            elem_of[row['a'][0]] = row['a'][1]

    out = []
    for name, e in sorted(enemies.items(), key=lambda kv: (kv[1]['lvl'], kv[0])):
        area = e['area']
        dungeons = [i for i, d in enumerate(DUNGEONS) if re.search(r'(^|, )' + re.escape(d) + r'(?![A-Za-z])', area)]
        if not dungeons:
            sys.exit('area without a known dungeon: %r (%s)' % (area, name))
        unknown = [s for s in e['skills'] if s not in elem_of]
        if unknown:
            sys.exit('unknown skills of %s: %s' % (name, unknown))
        attacks = sorted({ATTACKS.index(elem_of[s]) for s in e['skills'] if elem_of[s] in ATTACKS})
        hp, sp, st, ma, de, ag, lu = e['stats']
        row = {'n': name, 'a': e['race'].replace(' P', ''), 'l': e['lvl'], 'h': hp, 'm': sp,
               's': [st, ma, de, ag, lu], 'x': ''.join(RESIST[c] for c in e['resists']),
               'k': e['skills'], 't': attacks, 'd': sorted(e.get('drops', {}).items(), key=lambda kv: -kv[1]),
               'w': area, 'g': dungeons, 'e': e['exp'], 'y': e['price']}
        if e['race'].endswith(' P'):
            row['p'] = 1  # the source files these under a separate "P" arcana: sub-bosses and rare Hands
        out.append(row)

    commit = subprocess.run(['git', '-C', str(src), 'rev-parse', '--short', 'HEAD'],
                            capture_output=True, text=True).stdout.strip()
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    target = WWW / 'shadow-data.js'
    target.write_text(
        '/* Generated by tools/gen_shadow_data.py - do not edit.\n'
        ' * Source: https://github.com/aqiu384/megaten-fusion-tool %s (Unlicense, public domain). */\n'
        'window.P4G_SHADOW_DATA={\n"dungeons":%s,\n"enemies":[\n%s\n]};\n'
        % (commit, dump(DUNGEONS), ',\n'.join(dump(r) for r in out)), encoding='utf-8')
    print('%d enemies, %d dungeons -> %s' % (len(out), len(DUNGEONS), target))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
