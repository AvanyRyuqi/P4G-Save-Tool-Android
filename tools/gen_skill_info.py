#!/usr/bin/env python3
"""Regenerates skill-info.js and persona-data.js (app/src/main/assets/www) from aqiu384/megaten-fusion-tool (Unlicense).

    git clone --depth 1 https://github.com/aqiu384/megaten-fusion-tool
    python tools/gen_skill_info.py megaten-fusion-tool

The source is keyed by the same numeric skill ids the save file uses. Effect text is composed the
same way the website does it (src/app/pq2/models/skill-importer.ts).
"""
import json
import pathlib
import sys

COST_UNITS = {2: '% HP', 5: ' SP'}


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def cost_text(raw):
    # The source packs the cost as: <= 1000 -> % of HP, > 1000 -> (raw - 1000) SP.
    if not raw:
        return ''
    if raw > 2000:
        raise SystemExit('unexpected cost encoding: %d' % raw)
    return str(raw - 1000) + COST_UNITS[5] if raw > 1000 else str(raw) + COST_UNITS[2]


def num(x):
    return str(int(x)) if float(x).is_integer() else ('%.4f' % x).rstrip('0')


def level_value(level):
    """0 = innate, int = Persona level, str = the website's code for a special party-member unlock."""
    if level < 2:
        return 0
    if level < 120:
        return int(level)
    level = int(level)
    return chr(level // 100 + 32) + chr(level % 100 + 32)


def effect_text(nums, descs, templates):
    _rank, _cost, power, lo, hi, acc, crit, mod = nums
    effect, cond, _card = descs
    template = templates[cond[3:]] if cond.startswith('FMT') else cond
    value = num(mod) if mod < 1000 else num((mod - 1000) / 100)
    parts = [
        '√%s pwr' % num(power) if power else '',
        '%d-%d hits' % (lo, hi) if lo != hi else ('%d hits' % hi if hi >= 2 else ''),
        '' if acc == 0 or 90 <= acc <= 110 else '%d%% acc' % acc,
        '' if crit <= 5 else '%d%% crit' % crit,
        '' if cond == '-' else template.replace('$1', value, 1).replace('$2', effect, 1),
    ]
    text = ', '.join(p for p in parts if p)
    return text if text.startswith('x') else text[:1].upper() + text[1:]


# spellings that differ between the source and the app's database (db.js)
PERSONA_ALIASES = {
    'Andras': 'Andra', 'Fuu-Ki': 'Fuu-ki', 'Hitokoto-Nushi': 'Hitokotonusi', 'Kin-Ki': 'Kin-ki',
    'Okuninushi': 'Oukuninushi', 'Ongyo-Ki': 'Ongyo-ki', 'Seiryu': 'Seiryuu', 'Sui-Ki': 'Sui-ki',
    'Yamata-no-Orochi': 'Yamatano-Orochi', 'Yomotsu-Ikusa': 'Ikusa', 'Kushinada-Hime': 'Kushinada', 'Lakshmi': 'Laksmi',
}
# evolved party Personas only have resistances in the source: base -> (second form, third form)
PARTY_FORMS = {
    'Jiraiya': ('Susano-O', 'Takehaya Susano-o'), 'Tomoe': ('Suzuka Gongen', 'Haraedo-no-Okami'),
    'Konohana Sakuya': ('Amaterasu', 'Sumeo-Okami'), 'Take-Mikazuchi': ('Rokuten Maoh', 'Takeji Zaiten'),
    'Himiko': ('Kanzeon', 'Kouzeon'), 'Kintoki-Douji': ('Kamui', 'Kamui-Moshiri'),
    'Sukuna-Hikona': ('Yamato Takeru', 'Yamato Sumeragi'),
}
# typo in golden-fusion-chart.json (the non-Golden chart has "Hanged" for the same pair)
RACE_TYPOS = {'Hang': 'Hanged'}


def write_js(filename, text):
    target = pathlib.Path(__file__).resolve().parent.parent / 'app/src/main/assets/www' / filename
    target.write_text('/* Generated by tools/gen_skill_info.py - do not edit.\n'
                      ' * Source: https://github.com/aqiu384/megaten-fusion-tool (Unlicense, public domain). */\n' + text,
                      encoding='utf-8')
    return target


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def persona_data(data, personas, skill_ids):
    db = load(pathlib.Path(__file__).resolve().parent.parent / 'tests/db.json')['personae']

    def pid(name):
        return db.index(PERSONA_ALIASES.get(name, name))  # raises on an unknown name

    chart = load(data / 'golden-fusion-chart.json')
    races, size = chart['races'], len(chart['races'])
    # like the website: two-Persona fusion uses the part of the table above the diagonal
    pairs = []
    for i in range(size):
        for j in range(i + 1, size):
            result = RACE_TYPOS.get(chart['table'][i][j], chart['table'][i][j])
            if result != '-':
                if result not in races:
                    raise SystemExit('unknown arcana in fusion chart: ' + result)
                pairs.append([i, j, races.index(result)])

    # arcana missing from the chart (World: special recipe only) still need a name
    for e in personas.values():
        if e['race'].replace(' P', '') not in races:
            races = races + [e['race'].replace(' P', '')]

    unlocks = {}
    for group in load(data / 'golden-demon-unlocks.json'):
        for names, condition in group['conditions'].items():
            for name in names.split(','):
                unlocks[name] = condition

    out = {}
    for name, e in personas.items():
        entry = {'a': races.index(e['race'].replace(' P', '')),
                 'l': e['lvl'], 's': e['stats'], 'r': e['resists'],
                 'k': sorted(([skill_ids[k], level_value(v)] for k, v in e['skills'].items() if k in skill_ids),
                             key=lambda x: (isinstance(x[1], str), x[1] if not isinstance(x[1], str) else 0))}
        if e.get('fusion') == 'party':
            entry['p'] = 1
        if name in unlocks:
            entry['u'] = unlocks[name]
        out[pid(name)] = entry

    forms = {}
    for base, (second, third) in PARTY_FORMS.items():
        for name, field in ((second, 'sesists'), (third, 'sfsists')):
            forms[pid(name)] = {'b': pid(base), 'r': personas[base][field]}

    special = {pid(k): [pid(n) for n in v] for k, v in load(data / 'special-recipes.json').items()}
    rows = ',\n'.join('"%d":%s' % (k, compact(out[k])) for k in sorted(out))
    return write_js('persona-data.js', 'window.P4G_PERSONA_DATA={\n"races":%s,\n"chart":%s,\n"special":%s,\n"forms":%s,\n"personas":{\n%s\n}};\n'
                    % (compact(races), compact(pairs), compact(special), compact(forms), rows)), len(out)


def main(src):
    app = pathlib.Path(src) / 'src' / 'app'
    data = app / 'p4' / 'data'
    templates = load(app / 'compendium' / 'data' / 'skill-effects.json')
    skills = {**load(data / 'skill-data.json'), **load(data / 'golden-skill-data.json')}

    personas = {}
    for name in ('demon-data.json', 'golden-demon-data.json', 'party-data.json', 'golden-party-data.json'):
        for persona, entry in load(data / name).items():
            personas[persona] = {**personas.get(persona, {}), **entry}
    learned = {}
    for persona, entry in sorted(personas.items()):
        for skill, level in entry.get('skills', {}).items():
            learned.setdefault(skill, []).append([persona, level_value(level)])

    out = {}
    for key, row in sorted(skills.items(), key=lambda kv: int(kv[0])):
        (name, elem, target), nums, descs = row['a'], row['b'], row['c']
        info = {'n': name, 'e': elem}
        if target != '-':
            info['t'] = target
        elif elem in ('sup', 'rec'):  # the website shows "-" as Self; for attacks it just means "not listed"
            info['t'] = 'Self'
        if cost_text(nums[1]):
            info['c'] = cost_text(nums[1])
        if effect_text(nums, descs, templates):
            info['d'] = effect_text(nums, descs, templates)
        if descs[2] != '-':
            info['k'] = descs[2]
        if name in learned:
            info['l'] = sorted(learned[name], key=lambda x: (isinstance(x[1], str), x[1], x[0]))
        out[int(key)] = info

    body = ',\n'.join('"%d":%s' % (k, compact(v)) for k, v in out.items())
    print('%d skills -> %s' % (len(out), write_js('skill-info.js', 'window.P4G_SKILL_INFO={\n' + body + '\n};\n')))
    # ids from 610 up are internal entries that cannot be selected in the editor
    skill_ids = {row['a'][0]: int(k) for k, row in skills.items() if int(k) < 610}
    target, count = persona_data(data, personas, skill_ids)
    print('%d personas -> %s' % (count, target))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
