#!/usr/bin/env python3
"""Regenerates app/src/main/assets/www/skill-info.js from aqiu384/megaten-fusion-tool (Unlicense).

    git clone --depth 1 https://github.com/aqiu384/megaten-fusion-tool
    python tools/gen_skill_info.py megaten-fusion-tool

The source is keyed by the same numeric skill ids the save file uses. Effect text is composed the
same way the website does it (src/app/pq2/models/skill-importer.ts).
"""
import json
import pathlib
import sys

COST_UNITS = {2: '% HP', 5: ' SP'}


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def cost_text(raw):
    # The source packs the cost as: <= 1000 -> % of HP, > 1000 -> (raw - 1000) SP.
    if not raw:
        return ''
    if raw > 2000:
        raise SystemExit('unexpected cost encoding: %d' % raw)
    return str(raw - 1000) + COST_UNITS[5] if raw > 1000 else str(raw) + COST_UNITS[2]


def num(x):
    return str(int(x)) if float(x).is_integer() else ('%.4f' % x).rstrip('0')


def level_value(level):
    """0 = innate, int = Persona level, str = the website's code for a special party-member unlock."""
    if level < 2:
        return 0
    if level < 120:
        return int(level)
    level = int(level)
    return chr(level // 100 + 32) + chr(level % 100 + 32)


def effect_text(nums, descs, templates):
    _rank, _cost, power, lo, hi, acc, crit, mod = nums
    effect, cond, _card = descs
    template = templates[cond[3:]] if cond.startswith('FMT') else cond
    value = num(mod) if mod < 1000 else num((mod - 1000) / 100)
    parts = [
        '√%s pwr' % num(power) if power else '',
        '%d-%d hits' % (lo, hi) if lo != hi else ('%d hits' % hi if hi >= 2 else ''),
        '' if acc == 0 or 90 <= acc <= 110 else '%d%% acc' % acc,
        '' if crit <= 5 else '%d%% crit' % crit,
        '' if cond == '-' else template.replace('$1', value, 1).replace('$2', effect, 1),
    ]
    text = ', '.join(p for p in parts if p)
    return text if text.startswith('x') else text[:1].upper() + text[1:]


def main(src):
    app = pathlib.Path(src) / 'src' / 'app'
    data = app / 'p4' / 'data'
    templates = load(app / 'compendium' / 'data' / 'skill-effects.json')
    skills = {**load(data / 'skill-data.json'), **load(data / 'golden-skill-data.json')}

    personas = {}
    for name in ('demon-data.json', 'golden-demon-data.json', 'party-data.json', 'golden-party-data.json'):
        for persona, entry in load(data / name).items():
            personas[persona] = {**personas.get(persona, {}), **entry}
    learned = {}
    for persona, entry in sorted(personas.items()):
        for skill, level in entry.get('skills', {}).items():
            learned.setdefault(skill, []).append([persona, level_value(level)])

    out = {}
    for key, row in sorted(skills.items(), key=lambda kv: int(kv[0])):
        (name, elem, target), nums, descs = row['a'], row['b'], row['c']
        info = {'n': name, 'e': elem}
        if target != '-':
            info['t'] = target
        elif elem in ('sup', 'rec'):  # the website shows "-" as Self; for attacks it just means "not listed"
            info['t'] = 'Self'
        if cost_text(nums[1]):
            info['c'] = cost_text(nums[1])
        if effect_text(nums, descs, templates):
            info['d'] = effect_text(nums, descs, templates)
        if descs[2] != '-':
            info['k'] = descs[2]
        if name in learned:
            info['l'] = sorted(learned[name], key=lambda x: (isinstance(x[1], str), x[1], x[0]))
        out[int(key)] = info

    target = pathlib.Path(__file__).resolve().parent.parent / 'app/src/main/assets/www/skill-info.js'
    body = ',\n'.join('"%d":%s' % (k, json.dumps(v, ensure_ascii=False, separators=(',', ':'))) for k, v in out.items())
    target.write_text('/* Generated by tools/gen_skill_info.py - do not edit.\n'
                      ' * Source: https://github.com/aqiu384/megaten-fusion-tool (Unlicense, public domain). */\n'
                      'window.P4G_SKILL_INFO={\n' + body + '\n};\n', encoding='utf-8')
    print('%d skills -> %s' % (len(out), target))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
